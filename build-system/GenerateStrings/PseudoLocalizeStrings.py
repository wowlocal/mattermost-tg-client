# MATTERMOST: pseudo-localization of the merged English strings (Telegram/BUILD `RelayPseudoLocalizableStrings`,
# debug builds only; docs/design/localization.md). Every value becomes accented, about a third longer and
# bracketed: "Log In" → "⟦Ļööĝ Îîñ⟧". Running the app with `-AppleLanguages "(en-XA)"` then shows
# - text that stays plain English: a hard-coded string (or server data), not from the strings files;
# - a missing "⟧": a truncated or clipped label;
# - doubled vowels: room for languages that run longer than English.
# Format arguments (%@, %1$@, %d, %%), escapes (\n, \"), {placeholders}, markdown link targets and URLs are kept.
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from GenerateStrings import _get_content  # noqa: E402

_comment = r'(?:/\*(?P<comment>(?:[^*]|(?:\*+[^*/]))*\**)\*/)'
_entry = re.compile(r'(?:%s[ \t]*[\n]|[\r\n]|[\r])?(?P<line>(("(?P<key>[^"\\]*(?:\\.[^"\\]*)*)")|('
                    r'?P<property>\w+))\s*=\s*"(?P<value>[^"\\]*(?:\\.[^"\\]*)*)"\s*;)' % _comment, re.DOTALL | re.U)

# Kept as they are, in this order of precedence.
_protected = re.compile(
    r'\\U[0-9A-Fa-f]{4}'                                            # \U2026
    r'|\\.'                                                         # \n, \", \\
    r'|%(?:\d+\$)?[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l|q|z|t|j)?[@dDiuUxXoOfFeEgGaAcCsSp%]'  # format arguments
    r'|\]\([^)]*\)'                                                 # markdown link targets: [text](url)
    r'|\{[A-Za-z0-9_]+\}'                                           # {placeholders}
    r'|[A-Za-z][A-Za-z0-9+.-]*://\S*'                               # URLs
    r'|<[^>]*>',                                                    # inline tags
    re.U)

_accents = dict(zip(
    'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ',
    'åƀçðéƒĝĥîĵķļɱñöþǫŕšţûṽŵẋýžÅƁÇÐÉƑĜĤÎĴĶĻṀÑÖÞǪŔŠŢÛṼŴẊÝŽ'))
_vowels = set('aeiouAEIOU')


def _pseudo_text(text):
    result = []
    for character in text:
        accented = _accents.get(character, character)
        result.append(accented)
        if character in _vowels:
            # Doubling vowels makes words ~35% longer and keeps them words (they still wrap like words).
            result.append(accented.lower() if character.isupper() else accented)
    return ''.join(result)


def pseudo_value(key, value):
    if not value or not re.search(r'[A-Za-z]', _protected.sub('', value)):
        return value
    if key.endswith('URL') or key.endswith('Url') or re.fullmatch(r'\s*[A-Za-z][A-Za-z0-9+.-]*:\S*\s*', value):
        return value
    pieces = []
    position = 0
    for match in _protected.finditer(value):
        pieces.append(_pseudo_text(value[position:match.start()]))
        pieces.append(match.group(0))
        position = match.end()
    pieces.append(_pseudo_text(value[position:]))
    return u'\u27e6' + ''.join(pieces) + u'\u27e7'


def pseudo_localize(source_path, output_path):
    content = (_get_content(source_path) or '').lstrip(u'\ufeff')
    lines = []
    for match in _entry.finditer(content):
        key = match.group('key') or match.group('property')
        lines.append('"%s" = "%s";' % (key, pseudo_value(key, match.group('value'))))
    with open(output_path, 'w', encoding='utf-8') as file:
        file.write('/* Generated by PseudoLocalizeStrings.py from the merged English strings. */\n')
        file.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    pseudo_localize(args.source, args.output)
