import Foundation

/// Built-in Mattermost emoji short names → Unicode. Names not in the table are treated as
/// (possibly custom) emoji and get a `customEmoji` entity.
///
/// Each row lists one or more space-separated aliases. Emoji that need a variation selector
/// (U+FE0F) or ZWJ sequences are written with explicit escapes.
public enum EmojiTable {
    public static func unicode(forName name: String) -> String? {
        return table[name]
    }

    /// Every known short name (including aliases).
    public static var allNames: [String] {
        return Array(table.keys)
    }

    private static let table: [String: String] = {
        var result: [String: String] = [:]
        result.reserveCapacity(rows.count * 2)
        for (names, emoji) in rows {
            for name in names.split(separator: " ") {
                result[String(name)] = emoji
            }
        }
        return result
    }()

